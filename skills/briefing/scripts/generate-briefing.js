#!/usr/bin/env node

/**
 * generate-briefing.js
 * Formats and writes a briefing from data provided by the agent.
 * The agent fetches weather (via Open-Meteo) and news (via web_search tool).
 * This script formats and writes the briefing.
 * 
 * Usage: node generate-briefing.js <morning|evening> <weatherJson> <newsJson>
 * 
 * Weather JSON: {"temp":"15°C","condition":"Clear","wind":"10 km/h","location":"Sandy, UT"}
 * News JSON: [{"title":"...","url":"...","snippet":"..."},...]
 */

const fs = require('fs');
const path = require('path');

const OUTPUT_DIR = '/home/ubuntu/.openclaw/workspace/mission-control/briefings';

function getDatePaths() {
  const now = new Date();
  const yyyy = String(now.getUTCFullYear());
  const mm = String(now.getUTCMonth() + 1).padStart(2, '0');
  const dd = String(now.getUTCDate()).padStart(2, '0');
  const timeStr = now.toISOString().split('T')[1].slice(0, 5);
  return { yyyy, mm, dd, timeStr };
}

function categorize(news) {
  const ai = [], tech = [], abraxas = [], local = [];
  news.forEach(item => {
    const text = `${item.title} ${item.snippet}`.toLowerCase();
    let entry = `- [_${item.url}_|${item.snippet}]\n`;
    if (text.includes('artificial intelligence') || text.includes('large language model') || 
        text.includes(' ai ') || text.includes('gpt') || text.includes('claude') || 
        text.includes('llm') || text.includes('neural') || text.includes('agent')) {
      ai.push(entry);
    } else if (text.includes('abraxas')) {
      abraxas.push(entry);
    } else if (text.includes('utah') || text.includes('salt lake') || text.includes('84015')) {
      local.push(entry);
    } else {
      tech.push(entry);
    }
  });
  return { ai, tech, abraxas, local };
}

function formatBriefing(type, weather, news, datePaths) {
  const { yyyy, mm, dd, timeStr } = datePaths;
  const title = type === 'morning' ? 'Morning' : 'Evening';
  const { ai, tech, abraxas, local } = categorize(news);

  let lines = [
    `# ${title} Briefing — ${yyyy}-${mm}-${dd} (${timeStr} UTC)\n`,
    `_\`Generated by Mary Jane — Mission Control\`_\n`,
  ];

  lines.push('\n## AI News\n');
  lines.push(ai.length ? ai.join('') : '- No significant AI news today.\n');

  lines.push('\n## Technology\n');
  lines.push(tech.length ? tech.join('') : '- No significant tech news today.\n');

  lines.push('\n## Abraxas\n');
  lines.push(abraxas.length ? abraxas.join('') : '- No specific Abraxas news today.\n');

  lines.push('\n## Local (84015 — Sandy, UT)\n');
  lines.push(local.length ? local.join('') : '- No significant local news today.\n');

  lines.push('\n## Weather (84015)\n');
  lines.push(`- **${weather.condition || 'N/A'}**, Temp: ${weather.temp || 'N/A'}, Wind: ${weather.wind || 'N/A'}\n`);

  lines.push('\n## Sources\n');
  const seen = new Set();
  news.forEach(n => { if (!seen.has(n.url)) { seen.add(n.url); lines.push(`- ${n.url}\n`); } });

  return lines.join('');
}

const [,, type, weatherJson, newsJson] = process.argv;

if (!type || !weatherJson || !newsJson) {
  console.error('Usage: node generate-briefing.js <morning|evening> <weatherJson> <newsJson>');
  process.exit(1);
}

const weather = JSON.parse(decodeURIComponent(weatherJson));
const news = JSON.parse(decodeURIComponent(newsJson));
const datePaths = getDatePaths();
const { yyyy, mm, dd } = datePaths;

const briefing = formatBriefing(type, weather, news, datePaths);

const dir = path.join(OUTPUT_DIR, yyyy, mm, dd);
fs.mkdirSync(dir, { recursive: true });
const filepath = path.join(dir, `${type}-briefing.md`);
fs.writeFileSync(filepath, briefing);

console.log(`\n✓ Briefing written: ${filepath}`);
console.log(`  Weather: ${weather.condition}, ${weather.temp}`);
console.log(`  AI: ${news.filter(n => 'artificial intelligence large language model ai gpt claude llm'.some(w => `${n.title} ${n.snippet}`.toLowerCase().includes(w))).length} items`);
console.log(`  Tech: ${news.filter(n => !'artificial intelligence large language model ai gpt claude llm abraxas utah salt lake 84015'.some(w => `${n.title} ${n.snippet}`.toLowerCase().includes(w))).length} items`);

console.log('\n__BRIEFING_DATA__');
console.log(JSON.stringify({ success: true, type, yyyy, mm, dd, filepath, newsCount: news.length }));
