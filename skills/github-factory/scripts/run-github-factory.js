#!/usr/bin/env node

/**
 * run-github-factory.js
 * Fetches GitHub activity for TylerGarlick and writes a report.
 * 
 * Usage: node run-github-factory.js <taskId>
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const TASKS_FILE = path.join(__dirname, '../../tasks.json');
const GITHUB_TOKEN = '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';
const USERNAME = 'TylerGarlick';

function loadTasks() {
  return JSON.parse(fs.readFileSync(TASKS_FILE, 'utf8'));
}

function githubGet(endpoint) {
  return new Promise((resolve, reject) => {
    const url = `https://api.github.com${endpoint}`;
    const options = {
      headers: {
        'Authorization': `token ${GITHUB_TOKEN}`,
        'User-Agent': 'MaryJane-MissionControl/1.0',
        'Accept': 'application/vnd.github.cloak-preview+json'
      }
    };
    https.get(url, options, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => {
        try { resolve(JSON.parse(data)); }
        catch (e) { reject(new Error(`Failed to parse GitHub API response for ${endpoint}`)); }
      });
    }).on('error', reject);
  });
}

async function fetchRecentRepos() {
  const data = await githubGet(`/users/${USERNAME}/repos?sort=updated&per_page=30`);
  return Array.isArray(data) ? data.slice(0, 10).map(r => ({
    name: r.full_name,
    description: r.description,
    language: r.language,
    updated: r.updated_at,
    stars: r.stargazers_count,
    forks: r.forks_count
  })) : [];
}

async function fetchRecentEvents() {
  const events = await githubGet(`/users/${USERNAME}/events?per_page=50`);
  if (!Array.isArray(events)) return [];
  
  const commits = [];
  const creates = [];
  
  for (const e of events) {
    if (e.type === 'PushEvent' && e.payload?.commits) {
      for (const c of e.payload.commits) {
        commits.push({
          repo: e.repo.name,
          message: c.message.split('\n')[0],
          date: e.created_at
        });
      }
    }
    if (e.type === 'CreateEvent' && e.payload?.ref_type === 'repository') {
      creates.push({
        repo: e.repo.name,
        ref: e.payload.ref || 'unknown',
        date: e.created_at
      });
    }
  }
  
  return { commits: commits.slice(0, 20), newRepos: creates.slice(0, 10) };
}

async function generateReport(taskId) {
  const task = loadTasks().tasks.find(t => t.id === taskId);
  const taskDir = path.join(__dirname, '../../tasks', taskId, 'github');
  fs.mkdirSync(taskDir, { recursive: true });
  
  const { commits, newRepos } = await fetchRecentEvents();
  const repos = await fetchRecentRepos();
  
  // Known active repos
  const knownActive = ['curiosity-hour', 'Abraxas', 'outerspace'];
  const activeRepos = repos.filter(r => {
    const name = r.name;
    return knownActive.some(a => name.includes(a) || name.toLowerCase().includes(a));
  });
  
  const md = `# GitHub Activity Report — ${new Date().toISOString().split('T')[0]}

## Recent Commits

${commits.length === 0 ? '_No commits found in recent events._' : commits.map(c =>
`### [${c.repo}] ${c.message}
- ${c.date}`
).join('\n')}

## New Repositories Created

${newRepos.length === 0 ? '_No new repos created._' : newRepos.map(n =>
`- **${n.ref}** — created ${n.date}`
).join('\n')}

## Active Repositories

| Repo | Language | Stars | Forks | Last Updated |
|------|----------|-------|-------|--------------|
${activeRepos.map(r => `| ${r.name} | ${r.language || '—'} | ${r.stars} | ${r.forks} | ${r.updated.split('T')[0]} |`).join('\n')}

## All Recent Repositories

| Repo | Description | Language | Updated |
|------|-------------|----------|---------|
${repos.map(r => `| ${r.name} | ${r.description || '—'} | ${r.language || '—'} | ${r.updated.split('T')[0]} |`).join('\n')}

## Summary

- Active projects: ${knownActive.join(', ')}
- Total commits in window: ${commits.length}
- New repos: ${newRepos.length}

---
*Generated by Mary Jane — GitHub Factory*
`;

  fs.writeFileSync(path.join(taskDir, 'report.md'), md);
  console.log(`✓ GitHub report written to ${taskDir}/report.md`);
  console.log(`  Commits: ${commits.length}, New repos: ${newRepos.length}, Repos: ${repos.length}`);
}

const [,, taskId] = process.argv;
if (!taskId) {
  console.error('Usage: node run-github-factory.js <taskId>');
  process.exit(1);
}

generateReport(taskId).catch(err => {
  console.error('Error:', err.message);
  process.exit(1);
});
